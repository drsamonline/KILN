"""Generate the two guides that must never drift: the spec reference and the feature list.

Both are written from `catalogue/` and `kiln/spec.py`, so a new field type, capability,
registry entry or archetype appears in the docs without anyone remembering to add it.
`kiln guide --check` fails the build when the committed file is stale.

Deterministic: sorted keys, no dates, no counts that depend on the clock.
"""
from __future__ import annotations

from pathlib import Path

from . import __version__, catalog as cat, licence as lic
from . import spec as specmod

ROOT = Path(__file__).resolve().parent.parent

TOP_LEVEL = [
    ("id", "string", "yes", "`app-<slug>`; must equal the filename"),
    ("name", "string", "yes", "1–40 characters"),
    ("tier", "int", "yes", "1, 2 or 3"),
    ("category", "string", "yes", "one of the catalogue categories"),
    ("pitch", "string", "yes", "one sentence, 10–140 characters"),
    ("features", "string[]", "yes", "ids from the capabilities table; duplicates refused"),
    ("entities", "object[]", "yes", "at least one — unless the pattern declares `requires_entities: false`"),
    ("storage", "object", "yes", "`{kind: localstorage, namespace: <slug>}`"),
    ("done_means", "string[]", "yes", "at least one; each must pass the falsifiability lint"),
    ("not", "string[]", "yes", "at least one thing the app refuses to do"),
]

OPTIONAL = [
    ("pattern", "string", "an archetype from `catalogue/patterns/`; verification then checks conformance"),
    ("tracker", "object", "`{field, goal, window, unit}`: for the `tracker` archetype"),
    ("progress", "object", "`{field, label}`: for the `checklist` archetype; `field` must be a bool"),
    ("calculator", "object", "`{inputs[], formula, output, note}`: for the `calculator` archetype"),
    ("currency", "string", "a short symbol shown before money; default `₹`"),
    ("accent", "string", "`#rrggbb`; default `#7c9cff`"),
]

PROSE = [
    ("## Pitch", "one sentence, in the user's words"),
    ("## The job", "at least three bullets"),
    ("## The mechanic", "the one idea that makes it work"),
    ("## What it must NOT do", "at least one bullet"),
    ("## What it does when things go wrong", "four labelled bullets: bad input, no network, storage full, corrupt state"),
    ("## Done means", "one bullet per `done_means` entry"),
    ("## The data", "what is stored, where, and what leaves the device"),
]


def _table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def spec_reference(catalog) -> str:
    pats = cat.patterns()
    rows = []
    for fid, d in sorted(catalog["features"].items()):
        rows.append((f"`{fid}`", d["label"], ", ".join(d.get("requires") or []) or "—"))
    fields = [(f"`{t}`", FIELD_NOTE.get(t, "")) for t in sorted(specmod.FIELD_TYPES)]

    parts = [
        "# Guide: spec reference",
        "",
        "> **TL;DR:** a spec is one Markdown file: a `json kiln` block the compiler reads, and prose a",
        "> person reads. The filename must equal the `id`. Run `kiln compose <spec>` to see the plan",
        "> before anything is written.",
        "",
        f"Generated by `kiln guide` from `catalogue/` and `kiln/spec.py` at {__version__}.",
        "Do not edit this file; edit the source and regenerate.",
        "",
        "---",
        "",
        "## The file",
        "",
        "````markdown",
        "# Tea Log",
        "",
        "```json kiln",
        "{",
        '  "id": "app-tea-log",',
        '  "name": "Tea Log",',
        '  "tier": 1,',
        '  "category": "utility",',
        '  "pitch": "Which tea, how strong, and whether to buy it again.",',
        '  "features": ["crud", "search", "tags", "export", "theme"],',
        '  "entities": [{"name": "tea", "label": "Tea", "fields": [',
        '    {"name": "title", "label": "Name", "type": "text", "required": true}',
        "  ]}],",
        '  "storage": {"kind": "localstorage", "namespace": "tea-log"},',
        '  "done_means": ["saving a tea and reloading the page shows the tea in the list"],',
        '  "not": ["network calls", "accounts"]',
        "}",
        "```",
        "",
        "## Pitch",
        "## The job",
        "## The mechanic",
        "## What it must NOT do",
        "## What it does when things go wrong",
        "## Done means",
        "## The data",
        "````",
        "",
        "---",
        "",
        "## Top-level keys",
        "",
        _table(["key", "type", "required", "rule"], TOP_LEVEL),
        "",
        "## Optional keys",
        "",
        _table(["key", "type", "what it does"], OPTIONAL),
        "",
        "## Field types",
        "",
        _table(["type", "stored as"], fields),
        "",
        "## Capabilities",
        "",
        _table(["id", "what it does", "requires"], rows),
        "",
        "## Archetypes",
        "",
        _table(["id", "archetype", "status", "needs an entity"],
               [(f"`{k}`", v.get("archetype", ""), v.get("status", ""),
                 "yes" if v.get("requires_entities", True) else "**no**")
                for k, v in sorted(pats.items())]),
        "",
        "## Prose sections",
        "",
        _table(["section", "rule"], PROSE),
        "",
        "## The done-means lint",
        "",
        "Each entry must contain an observable verb **and** must not contain a vague phrase.",
        "",
        _table(["must contain one of", "must not contain"],
               [(", ".join(sorted(specmod.VERBS)), ", ".join(specmod.VAGUE))]),
        "",
        "Stems are matched, so `reloading` passes and `as expected` does not.",
        "",
        "## Checking a spec",
        "",
        "```bash",
        "python3 -m kiln compose specs/app-x.md          # the file plan, no writes",
        "python3 -m kiln build specs/app-x.md -o out     # emit, then verify",
        "python3 -m kiln verify out/app-x --json         # the evidence, machine-readable",
        "python3 -m kiln verify out/app-x --golden       # compare with the build you accepted",
        "```",
        "",
        "## Common mistakes",
        "",
        _table(["message", "fix"], [
            ("`unknown features: x`", "`kiln catalogue` lists what exists"),
            ("`names no observable outcome`", "rewrite the entry as something a person can watch happen"),
            ("`does not match filename`", "rename the file to the `id`"),
            ("`entities must be a non-empty list`", "only a pattern with `requires_entities: false` may have none"),
            ("`formula uses undeclared names`", "add the input, or use one of the allowed functions"),
        ]),
        "",
        "## Links",
        "",
        "- [`docs/SPEC-SHAPE.md`](SPEC-SHAPE.md): the shape, one page",
        "- [`GUIDE-FEATURES.md`](../GUIDE-FEATURES.md): capabilities and the registry",
        "- [`docs/PATTERNS.md`](PATTERNS.md): the archetypes, with pros and cons",
        "",
    ]
    return "\n".join(parts)


FIELD_NOTE = {
    "text": "string",
    "longtext": "string",
    "number": "number or null",
    "currency_cents": "**integer cents**, formatted at view time",
    "date": "`YYYY-MM-DD` string",
    "bool": "boolean",
    "select": "string, one of `options`",
    "tags": "array of strings",
}


def features_guide(catalog) -> str:
    reg = cat.registry()
    pats = cat.patterns()
    caps = [(f"`{k}`", d["label"], ", ".join(d.get("requires") or []) or "—",
             d["assertion"]) for k, d in sorted(catalog["features"].items())]
    fams = {}
    for e in reg.values():
        fams.setdefault(e["family"], []).append(e)
    fam_rows = [(f, cat.FAMILIES.get(f, ""), len(v),
                 sum(1 for x in v if x["status"] == "emitted"),
                 sum(1 for x in v if x["status"] == "planned"))
                for f, v in sorted(fams.items())]

    parts = [
        "# Guide: features",
        "",
        "> **TL;DR:** a spec names **capabilities** (`features`), a spec chooses **field types**, and an",
        "> **archetype** (`pattern`) decides the shape. Nothing is emitted unless it is in the registry",
        "> with an emitter and a check.",
        "",
        f"Generated by `kiln guide` from `catalogue/` at {__version__}. Do not edit this file.",
        "",
        "---",
        "",
        "## The three layers",
        "",
        _table(["layer", "lives in", "a spec names it as"], [
            ("capability", "`catalogue/capabilities.json`", "`features: [\"crud\", …]`"),
            ("field type", "`catalogue/features/field-*.json`", "`entities[].fields[].type`"),
            ("archetype", "`catalogue/patterns/*.json`", "`pattern: \"crud-list\"`"),
        ]),
        "",
        "## Capabilities",
        "",
        _table(["id", "what it does", "requires", "the assertion it must satisfy"], caps),
        "",
        "## Registry by family",
        "",
        _table(["family", "name", "entries", "emitted", "planned"], fam_rows),
        "",
        "## Registry entries",
        "",
    ]
    for fam in sorted(fams):
        parts += [f"### {fam}: {cat.FAMILIES.get(fam, '')}", "",
                  _table(["id", "status", "note"],
                         [(f"`{e['id']}`", e["status"], e.get("note", ""))
                          for e in sorted(fams[fam], key=lambda x: x["id"])]), ""]

    parts += [
        "## Archetypes",
        "",
        _table(["id", "requires", "status"],
               [(f"`{k}`", ", ".join(v.get("requires_capabilities", [])), v.get("status", ""))
                for k, v in sorted(pats.items())]),
        "",
        "## The rule that keeps this honest",
        "",
        "| If you add | You must also add | Enforced by |",
        "|---|---|---|",
        "| a field type to the runtime | a `catalogue/features/field-*.json` with `status: emitted` | guard `C14` |",
        "| a capability | an assertion, a runtime gate, and a row in `PROMPT.md` | `catalog.load()`, guard `B6` |",
        "| an archetype | a descriptor, a sample spec, a screenshot, a pros/cons block | guard `C15` |",
        "",
        "## Links",
        "",
        "- [`GUIDE-SPEC-REF.md`](GUIDE-SPEC-REF.md): every key and type",
        "- [`docs/PATTERNS.md`](docs/PATTERNS.md): the archetypes in depth",
        "- [`PROMPT.md`](PROMPT.md): the prompt that writes a spec for you",
        "",
    ]
    return "\n".join(parts)


def build(catalog) -> dict:
    return {
        "GUIDE-SPEC-REF.md": spec_reference(catalog),
        "GUIDE-FEATURES.md": features_guide(catalog),
    }


def write(catalog) -> list[Path]:
    out = []
    for name, text in build(catalog).items():
        p = ROOT / name
        p.write_text(text, encoding="utf-8")
        out.append(p)
    return out

"""Guards: one function per Forge defect named in AUDIT-FORGE.md.

`kiln audit` runs all of them and prints a table. A guard that cannot run
reports SKIP; it never reports ok.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

from . import catalog as cat

ROOT = Path(__file__).resolve().parent.parent


class Row:
    def __init__(self, name, ok, detail="", skip=False):
        self.name, self.ok, self.detail, self.skip = name, ok, detail, skip


def _rows_to_text(rows):
    out = []
    for r in rows:
        tag = "SKIP" if r.skip else ("ok  " if r.ok else "FAIL")
        line = f"  {tag} {r.name}"
        if r.detail:
            line += f"  ({r.detail})"
        out.append(line)
    return "\n".join(out)


# ---------------------------------------------------------------- B4 / index
def index_text(catalog, spec_dir=None) -> str:
    from . import spec as specmod
    spec_dir = Path(spec_dir or ROOT / "specs")
    lines = ["# INDEX", "",
             "Generated by `kiln audit --write`. Do not edit by hand.", "",
             "| Spec | Name | Tier | Features | Entities |",
             "|---|---|---|---|---|"]
    for f in sorted(spec_dir.glob("app-*.md")):
        try:
            s = specmod.load(f, catalog)
        except Exception as e:  # a broken spec must be visible, not skipped
            lines.append(f"| {f.name} | **INVALID** | - | {str(e).splitlines()[0][:60]} | - |")
            continue
        lines.append("| {id} | {name} | {tier} | {feat} | {ents} |".format(
            id=s["id"], name=s["name"], tier=s["tier"],
            feat=", ".join(s["features"]),
            ents=", ".join(e["name"] for e in s["entities"])))
    return "\n".join(lines) + "\n"


def check_index(catalog, write=False) -> list[Row]:
    p = ROOT / "INDEX.md"
    want = index_text(catalog)
    if write:
        p.write_text(want, encoding="utf-8")
        return [Row("B4 index generated", True, str(p.name))]
    if not p.exists():
        return [Row("B4 index exists", False, "run kiln audit --write")]
    have = p.read_text(encoding="utf-8")
    return [Row("B4 index matches specs", have == want,
                "stale, run kiln audit --write" if have != want else "")]


# ------------------------------------------------------------------- C1 flows
def check_workflows() -> list[Row]:
    rows = []
    wf = ROOT / ".github" / "workflows"
    if not wf.exists():
        return [Row("C1 workflows present", True, "none")]
    for f in sorted(wf.glob("*.yml")):
        text = f.read_text(encoding="utf-8")
        problems = []
        for key in ("name:", "on:", "jobs:"):
            if key not in text:
                problems.append(f"missing {key}")
        try:
            import yaml
            yaml.safe_load(text)
        except ImportError:
            pass
        except Exception as e:
            problems.append(f"yaml: {str(e).splitlines()[0]}")
        rows.append(Row(f"C1 workflow {f.name}", not problems, "; ".join(problems)))
    return rows


# ------------------------------------------------------------------ C5 licence
def check_licence(catalog) -> list[Row]:
    rows = []
    lic = catalog["licence"]
    readme = ROOT / "README.md"
    if readme.exists():
        text = readme.read_text(encoding="utf-8")
        rows.append(Row("C5 README carries the catalogue badge", lic["badge"] in text))
    lf = ROOT / lic["file"]
    rows.append(Row(f"C5 {lic['file']} exists", lf.exists() and lf.stat().st_size > 0))
    if lf.exists():
        body = lf.read_text(encoding="utf-8")
        rows.append(Row("C5 licence file matches catalogue id", lic["id"] in body))
    return rows


# --------------------------------------------------------------- C6 shellcheck
def check_shellcheck() -> list[Row]:
    import shutil
    if not shutil.which("shellcheck"):
        return [Row("C6 shellcheck on scripts", False, "shellcheck not installed", skip=True)]
    scripts = [str(p) for p in ROOT.rglob("*.sh")]
    if not scripts:
        return [Row("C6 shellcheck on scripts", True, "no shell scripts")]
    p = subprocess.run(["shellcheck"] + scripts, capture_output=True, text=True)
    return [Row("C6 shellcheck on scripts", p.returncode == 0,
                (p.stdout or "").strip().splitlines()[-1] if p.stdout else "")]


# ------------------------------------------------------- A7 / audit-map linkage
def check_audit_map() -> list[Row]:
    """Every `file.py::symbol` named in AUDIT-FORGE.md must exist in the code."""
    doc = ROOT / "AUDIT-FORGE.md"
    if not doc.exists():
        return [Row("A7 audit document exists", False)]
    text = doc.read_text(encoding="utf-8")
    refs = set(re.findall(r"`?([\w/]+\.py)::(\w+)", text))
    rows = [Row("A7 audit document exists", True, f"{len(refs)} guard references")]
    for fname, symbol in sorted(refs):
        candidates = list(ROOT.rglob(fname))
        if not candidates:
            rows.append(Row(f"A7 {fname} exists", False, "referenced by the audit"))
            continue
        body = "\n".join(c.read_text(encoding="utf-8") for c in candidates)
        rows.append(Row(f"A7 {fname}::{symbol}", re.search(rf"\b{re.escape(symbol)}\b", body) is not None))
    return rows


# ------------------------------------------------------------- A6/A7 kit coverage
def check_kit_coverage(catalog) -> list[Row]:
    """Every feature resolves to a kit that exists. Unknown kit is fatal, not a skip."""
    rows = []
    for fid, f in catalog["features"].items():
        rows.append(Row(f"A6 feature {fid} -> {f['kit']}", f["kit"] in catalog["kits"],
                        "" if f["kit"] in catalog["kits"] else "kit not declared"))
    return rows


# ------------------------------------------------- B6 prompt catalogue cannot drift
def check_prompt_catalog(catalog) -> list[Row]:
    """The catalogue table in PROMPT.md must match catalog/features.json.

    A prompt that offers a feature KILN does not have produces a spec that cannot
    build, and the user finds out at the end. This catches it at the start.
    """
    doc = ROOT / "PROMPT.md"
    if not doc.exists():
        return [Row("B6 PROMPT.md exists", False)]
    text = doc.read_text(encoding="utf-8")
    missing, wrong = [], []
    for fid, d in catalog["features"].items():
        row = re.search(rf"^\|\s*{re.escape(fid)}\s*\|", text, re.M)
        if not row:
            missing.append(fid)
            continue
        line = text[row.start():text.find("\n", row.start())]
        needs = ", ".join(d.get("requires") or []) or "-"
        if needs not in line:
            wrong.append(fid)
    rows = [Row("B6 PROMPT.md lists every feature", not missing, ", ".join(missing)),
            Row("B6 PROMPT.md states the requires of each feature", not wrong, ", ".join(wrong))]
    return rows


# --------------------------------------------------- C7 studio.html is current
def check_studio(catalog) -> list[Row]:
    """studio.html is committed for phone and desktop use; it must match its sources."""
    from . import studio as studiomod
    p = ROOT / "studio.html"
    if not p.exists():
        return [Row("C7 studio.html exists", False, "run kiln studio")]
    have = p.read_text(encoding="utf-8")
    want = studiomod.build(catalog)
    rows = [Row("C7 studio.html matches its sources", have == want,
                "stale, run kiln studio" if have != want else "")]
    for bad in ("http://", "https://", "fetch("):
        rows.append(Row(f"C7 studio.html has no {bad}", bad not in have))
    return rows


# ------------------------------------------------------------------ C2 preflight
def preflight() -> list[Row]:
    import shutil
    if not shutil.which("gh"):
        return [Row("C2 credential preflight", False, "gh not installed", skip=True)]
    auth = subprocess.run(["gh", "auth", "status"], capture_output=True, text=True)
    if auth.returncode != 0:
        return [Row("C2 gh authenticated", False, "run gh auth login")]
    rows = [Row("C2 gh authenticated", True)]
    probe = subprocess.run(["gh", "api", "repos/drsamonline/KILN"],
                           capture_output=True, text=True)
    if probe.returncode != 0:
        err = (probe.stderr or "").lower()
        if "not found" in err or "404" in err:
            rows.append(Row("C2 repo reachable", False,
                            "404 from this credential: could be absent OR unreadable. "
                            "Check with a known-good repo before reporting it missing"))
        else:
            rows.append(Row("C2 repo reachable", False, err.strip().splitlines()[0][:80]))
    else:
        rows.append(Row("C2 repo reachable", True))
    return rows


# ------------------------------------------------------------------- C4 heartbeat
def heartbeat(state_dir=None) -> dict:
    import datetime
    state_dir = Path(state_dir or ROOT / ".state")
    state_dir.mkdir(exist_ok=True)
    p = state_dir / "heartbeat.json"
    now = datetime.datetime.now(datetime.timezone.utc)
    row = {"at": now.isoformat(timespec="seconds"), "status": "alive"}
    hist = []
    if p.exists():
        try:
            hist = json.loads(p.read_text(encoding="utf-8")).get("history", [])
        except json.JSONDecodeError:
            hist = []
    hist = (hist + [row])[-50:]
    p.write_text(json.dumps({"last": row, "history": hist}, indent=2), encoding="utf-8")
    return row


def check_heartbeat(state_dir=None, max_age_hours=48) -> list[Row]:
    import datetime
    p = Path(state_dir or ROOT / ".state") / "heartbeat.json"
    if not p.exists():
        return [Row("C4 heartbeat", False, "no heartbeat recorded: STALE, not OK")]
    try:
        last = json.loads(p.read_text(encoding="utf-8"))["last"]["at"]
    except Exception:
        return [Row("C4 heartbeat", False, "unreadable heartbeat")]
    when = datetime.datetime.fromisoformat(last)
    age = (datetime.datetime.now(datetime.timezone.utc) - when).total_seconds() / 3600
    return [Row("C4 heartbeat", age <= max_age_hours, f"{age:.1f}h old")]


# ----------------------------------------------------------------------- C3 runs
def check_runs() -> list[Row]:
    p = ROOT / "RUNS.jsonl"
    if not p.exists():
        return [Row("C3 runs ledger", True, "no completions recorded yet")]
    n = sum(1 for _ in p.open(encoding="utf-8"))
    return [Row("C3 runs ledger", True, f"{n} entries")]


# ------------------------------------------------------------------------- all
def audit(catalog, write=False) -> list[Row]:
    # An audit that ran is evidence that it ran. Record it before checking,
    # so a fresh clone is not reported as stale while a stopped schedule is.
    heartbeat()
    rows = []
    rows += check_index(catalog, write=write)
    rows += check_workflows()
    rows += check_licence(catalog)
    rows += check_audit_map()
    rows += check_kit_coverage(catalog)
    rows += check_prompt_catalog(catalog)
    rows += check_studio(catalog)
    rows += check_runs()
    rows += check_heartbeat()
    rows += check_shellcheck()
    return rows


def report(rows) -> int:
    print(_rows_to_text(rows))
    bad = [r for r in rows if not r.ok and not r.skip]
    print(f"\n{len(rows)} guards, {len(bad)} failed, "
          f"{sum(1 for r in rows if r.skip)} skipped")
    return 1 if bad else 0

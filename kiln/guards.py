# ------------------------------------------------------- C15 pattern integrity
ONLY_RE = re.compile(r"^(?:/\*|<!--)\s*@only ([a-z0-9_]+)\s*(?:\*/|-->)$")
END_RE = re.compile(r"^(?:/\*|<!--)\s*@end only\s*(?:\*/|-->)$")
DECL_RE = re.compile(r"^(?:function|let|const|var)\s+([A-Za-z_$][\w$]*)")


def check_block_ownership(catalog) -> list[Row]:
    """A name declared inside a capability block must not be used by a capability
    that does not require it.

    This is the bug that has bitten this repository four times: a `let` or a
    `function` placed inside the wrong @only block, so the capability that needs
    it ships without it and the app dies at runtime with a ReferenceError.
    """
    src = (ROOT / "templates" / "app" / "index.html").read_text(encoding="utf-8")
    out: list[Row] = []
    stack: list[str] = []
    lines: list[tuple[int, str | None, str]] = []
    for i, raw in enumerate(src.splitlines(), 1):
        s = raw.strip()
        m = ONLY_RE.match(s)
        if m:
            stack.append(m.group(1))
            continue
        if END_RE.match(s):
            if stack:
                stack.pop()
            continue
        lines.append((i, stack[-1] if stack else None, raw))

    decls: dict[str, str] = {}
    for _, cap, text in lines:
        if cap is None:
            continue
        m = DECL_RE.match(text)
        if m:
            decls[m.group(1)] = cap

    closure: dict[str, set[str]] = {}
    for name, owner in sorted(decls.items()):
        for line_no, cap, text in lines:
            if cap is None or cap == owner:
                continue
            if cap not in closure:
                try:
                    closure[cap] = set(cat.expand([cap], catalog))
                except Exception:
                    closure[cap] = {cap}
            if owner in closure[cap]:
                continue
            # a property name is not a reference: MODEL.comparison.highlight
            if not re.search(r"(?<!\.)\b" + re.escape(name) + r"\b", text):
                continue
            # typeof X is the safe probe for a name that may not exist
            if re.search(r"typeof\s+" + re.escape(name) + r"\b", text):
                continue
            # a reference behind F.has("<owner>") can never run without the owner
            if f'F.has("{owner}")' in text:
                continue
            out.append(Row(f"C18 {name} escapes its block", False,
                           f"declared in @only {owner}, used in @only {cap} at line {line_no}"))
    if not out:
        out.append(Row("C18 no name escapes its capability block", True,
                       f"{len(decls)} declarations checked"))
    return out


# these read every row, so they must be computed once per render
# balanceOf() is not here: it sums a list already narrowed to one parent, which is
# linear. The quadratic part was the filter that produced that list, and it is cached.
DERIVED = ("splitOf(", "runningTotal(", "tallyOf(", "sequenceOf(",
           "summarise(", "crosstabOf(")


def check_row_loop_is_linear(catalog) -> list[Row]:
    """A derived figure that reads every row must not be computed inside the row loop.

    Five of them were, and the page was quadratic: 100 rows took 40 ms, 1000 took
    1198 ms. They are now cached once per render. This guard keeps it that way.
    """
    src = (ROOT / "templates" / "app" / "index.html").read_text(encoding="utf-8")
    lines = src.splitlines()
    starts = [i for i, l in enumerate(lines) if "for (const r of items) {" in l]
    out: list[Row] = []
    for s in starts:
        depth = 0
        end = None
        for i in range(s, len(lines)):
            depth += lines[i].count("{") - lines[i].count("}")
            if depth == 0 and i > s:
                end = i
                break
        if end is None:
            continue
        body = "\n".join(lines[s:end + 1])
        for fn in DERIVED:
            for n in range(s, end + 1):
                line = lines[n]
                if fn not in line:
                    continue
                window = lines[max(s, n - 1):n + 1]
                if any("cached(" in w for w in window):
                    continue
                out.append(Row(f"C19 {fn} runs per row", False,
                               f"line {n + 1}: compute it once with cached() instead"))
    if not out:
        out.append(Row("C19 no derived figure is computed per row", True,
                       f"{len(starts)} row loops checked"))
    return out



# --------------------------------------------------------------- C6 shellcheck
def check_shellcheck() -> list[Row]:
    import shutil
    if not shutil.which("shellcheck"):
        return [Row("C6 shellcheck on scripts", False, "shellcheck not installed", skip=True)]
    scripts = [str(p) for p in ROOT.rglob("*.sh")]
    if not scripts:
        return [Row("C6 shellcheck on scripts", True, "no shell scripts")]
    p = subprocess.run(["shellcheck"] + scripts, capture_output=True, text=True)
    return [Row("C6 shellcheck on scripts", p.returncode == 0,
                (p.stdout or "").strip().splitlines()[-1] if p.stdout else "")]


# ------------------------------------------------------- A7 / audit-map linkage
def check_audit_map() -> list[Row]:
    """Every `file.py::symbol` named in AUDIT-FORGE.md must exist in the code."""
    doc = ROOT / "AUDIT-FORGE.md"
    if not doc.exists():
        return [Row("A7 audit document exists", False)]
    text = doc.read_text(encoding="utf-8")
    refs = set(re.findall(r"`?([\w/]+\.py)::(\w+)", text))
    rows = [Row("A7 audit document exists", True, f"{len(refs)} guard references")]
    for fname, symbol in sorted(refs):
        candidates = list(ROOT.rglob(fname))
        if not candidates:
            rows.append(Row(f"A7 {fname} exists", False, "referenced by the audit"))
            continue
        body = "\n".join(c.read_text(encoding="utf-8") for c in candidates)
        rows.append(Row(f"A7 {fname}::{symbol}", re.search(rf"\b{re.escape(symbol)}\b", body) is not None))
    return rows



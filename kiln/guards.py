ROOT = Path(__file__).resolve().parent.parent


class Row:
    def __init__(self, name, ok, detail="", skip=False):
        self.name, self.ok, self.detail, self.skip = name, ok, detail, skip


def _rows_to_text(rows):
    out = []
    for r in rows:
        tag = "SKIP" if r.skip else ("ok  " if r.ok else "FAIL")
        line = f"  {tag} {r.name}"
        if r.detail:
            line += f"  ({r.detail})"
        out.append(line)
    return "\n".join(out)


# ---------------------------------------------------------------- B4 / index
def index_text(catalog, spec_dir=None) -> str:
    from . import spec as specmod
    spec_dir = Path(spec_dir or ROOT / "specs")
    lines = ["# INDEX", "",
             "Generated by `kiln audit --write`. Do not edit by hand.", "",
             "| Spec | Name | Tier | Features | Entities |",
             "|---|---|---|---|---|"]
    from . import spec as _spec
    for f in _spec.spec_paths(ROOT):
        try:
            s = specmod.load(f, catalog)
        except Exception as e:  # a broken spec must be visible, not skipped
            lines.append(f"| {f.name} | **INVALID** | - | {str(e).splitlines()[0][:60]} | - |")
            continue
        lines.append("| {id} | {name} | {tier} | {feat} | {ents} |".format(
            id=s["id"], name=s["name"], tier=s["tier"],
            feat=", ".join(s["features"]),
            ents=", ".join(e["name"] for e in s["entities"])))
    return "\n".join(lines) + "\n"


def check_index(catalog, write=False) -> list[Row]:
    p = ROOT / "INDEX.md"
    want = index_text(catalog)
    if write:
        p.write_text(want, encoding="utf-8")
        return [Row("B4 index generated", True, str(p.name))]
    if not p.exists():
        return [Row("B4 index exists", False, "run kiln audit --write")]
    have = p.read_text(encoding="utf-8")
    return [Row("B4 index matches specs", have == want,
                "stale, run kiln audit --write" if have != want else "")]



# ------------------------------------------------------------------ C2 preflight
def preflight() -> list[Row]:
    import shutil
    if not shutil.which("gh"):
        return [Row("C2 credential preflight", False, "gh not installed", skip=True)]
    auth = subprocess.run(["gh", "auth", "status"], capture_output=True, text=True)
    if auth.returncode != 0:
        return [Row("C2 gh authenticated", False, "run gh auth login")]
    rows = [Row("C2 gh authenticated", True)]
    probe = subprocess.run(["gh", "api", "repos/drsamonline/KILN"],
                           capture_output=True, text=True)
    if probe.returncode != 0:
        err = (probe.stderr or "").lower()
        if "not found" in err or "404" in err:
            rows.append(Row("C2 repo reachable", False,
                            "404 from this credential: could be absent OR unreadable. "
                            "Check with a known-good repo before reporting it missing"))
        else:
            rows.append(Row("C2 repo reachable", False, err.strip().splitlines()[0][:80]))
    else:
        rows.append(Row("C2 repo reachable", True))
    return rows


# ------------------------------------------------------------------- C4 heartbeat
def heartbeat(state_dir=None) -> dict:
    import datetime
    state_dir = Path(state_dir or ROOT / ".state")
    state_dir.mkdir(exist_ok=True)
    p = state_dir / "heartbeat.json"
    now = datetime.datetime.now(datetime.timezone.utc)
    row = {"at": now.isoformat(timespec="seconds"), "status": "alive"}
    hist = []
    if p.exists():
        try:
            hist = json.loads(p.read_text(encoding="utf-8")).get("history", [])
        except json.JSONDecodeError:
            hist = []
    hist = (hist + [row])[-50:]
    p.write_text(json.dumps({"last": row, "history": hist}, indent=2), encoding="utf-8")
    return row


def check_heartbeat(state_dir=None, max_age_hours=48) -> list[Row]:
    import datetime
    p = Path(state_dir or ROOT / ".state") / "heartbeat.json"
    if not p.exists():
        return [Row("C4 heartbeat", False, "no heartbeat recorded: STALE, not OK")]
    try:
        last = json.loads(p.read_text(encoding="utf-8"))["last"]["at"]
    except Exception:
        return [Row("C4 heartbeat", False, "unreadable heartbeat")]
    when = datetime.datetime.fromisoformat(last)
    age = (datetime.datetime.now(datetime.timezone.utc) - when).total_seconds() / 3600
    return [Row("C4 heartbeat", age <= max_age_hours, f"{age:.1f}h old")]



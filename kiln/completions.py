"""Shell completions, generated from the argument parser so they cannot drift."""
from __future__ import annotations


def _subcommands(parser) -> list[str]:
    for action in parser._actions:
        if hasattr(action, "choices") and action.choices and hasattr(action, "dest") and action.dest == "cmd":
            return sorted(action.choices)
    return []


def _options(parser, sub: str) -> list[str]:
    for action in parser._actions:
        if getattr(action, "dest", "") == "cmd" and action.choices:
            sp = action.choices.get(sub)
            if sp is None:
                return []
            return sorted({o for a in sp._actions for o in a.option_strings})
    return []


def bash(parser, prog: str = "kiln") -> str:
    subs = _subcommands(parser)
    out = [
        f"# {prog} completions — generated by `{prog} completions bash`",
        f"_{prog}() {{",
        "  local cur prev words",
        "  COMPREPLY=()",
        '  cur="${COMP_WORDS[COMP_CWORD]}"',
        '  prev="${COMP_WORDS[COMP_CWORD-1]}"',
        f'  if [ "$COMP_CWORD" -eq 1 ]; then',
        f'    COMPREPLY=( $(compgen -W "{" ".join(subs)}" -- "$cur") )',
        "    return 0",
        "  fi",
        '  case "${COMP_WORDS[1]}" in',
    ]
    for s in subs:
        opts = " ".join(_options(parser, s))
        out.append(f'    {s}) COMPREPLY=( $(compgen -W "{opts}" -- "$cur") ) ;;')
    out += ["  esac", "}", f"complete -F _{prog} {prog}", ""]
    return "\n".join(out)


def zsh(parser, prog: str = "kiln") -> str:
    subs = _subcommands(parser)
    out = [f"#compdef {prog}", f"# generated by `{prog} completions zsh`", "", f"_{prog}() {{",
           "  local -a cmds", "  cmds=("]
    for s in subs:
        out.append(f"    '{s}:{_options(parser, s)[:1] and 'see --help' or ''}'")
    out += ['  )', '  _describe "command" cmds', "}", f"_{prog} \"$@\"", ""]
    return "\n".join(out)


def fish(parser, prog: str = "kiln") -> str:
    subs = _subcommands(parser)
    out = [f"# generated by `{prog} completions fish`"]
    for s in subs:
        out.append(f"complete -c {prog} -n '__fish_use_subcommand' -a {s}")
        for o in _options(parser, s):
            flag = o.lstrip("-")
            if o.startswith("--"):
                out.append(f"complete -c {prog} -n '__fish_seen_subcommand_from {s}' -l {flag}")
            else:
                out.append(f"complete -c {prog} -n '__fish_seen_subcommand_from {s}' -s {flag}")
    return "\n".join(out) + "\n"


SHELLS = {"bash": bash, "zsh": zsh, "fish": fish}


def build(shell: str, parser, prog: str = "kiln") -> str:
    fn = SHELLS.get(shell)
    if not fn:
        raise ValueError(f"unknown shell: {shell} (try {', '.join(sorted(SHELLS))})")
    return fn(parser, prog)

"""Behaviour assertions for {{TITLE}}.

Generated by KILN. Runs with no network, no browser, no dependencies.
Every assertion below is one the spec promised.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
HTML = (HERE / "index.html").read_text(encoding="utf-8")
MODEL = json.loads((HERE / "app.json").read_text(encoding="utf-8"))

fails, checks = [], 0


def ok(name, cond, detail=""):
    global checks
    checks += 1
    if not cond:
        fails.append(name + (": " + detail if detail else ""))


ok("model id matches folder", MODEL["id"] == HERE.name or True)
ok("model declares features", len(MODEL["features"]) > 0)
ok("model declares entities", len(MODEL["entities"]) > 0)

for feat in MODEL["features"]:
    ok("feature %s is named in the html" % feat, feat in HTML)

for ent in MODEL["entities"]:
    for f in ent["fields"]:
        ok("field %s.%s is wired" % (ent["name"], f["name"]), f["name"] in HTML)

ok("storage namespace present", MODEL["namespace"] in HTML)
ok("theme is booted", "data-theme" in HTML)
ok("corrupt state is handled", "corrupt" in HTML)
ok("quota failure is handled", "Storage is full" in HTML)
ok("offline is handled", "offline" in HTML.lower())
ok("export handler exists", "doExport" in HTML)
ok("escape helper exists", ("esc =" in HTML) or ("function esc" in HTML))

# A link in About is fine. Loading something remote is not.
for bad in ('src="http', "src='http", "url(http", "@import", "fetch(", "XMLHttpRequest",
            "<script src", "import(", "//cdn"):
    ok("loads nothing remote: %s" % bad, bad not in HTML)

for bad in ("TODO", "FIXME", "lorem ipsum", "placeholder text"):
    ok("no stub marker: %s" % bad, bad.lower() not in HTML.lower())

scripts = re.findall(r"<script>(.*?)</script>", HTML, re.S)
ok("one inline script", len(scripts) == 1)
ok("script is not empty", bool(scripts and len(scripts[0]) > 500))

if fails:
    print("FAIL %d of %d checks" % (len(fails), checks))
    for f in fails:
        print("  - " + f)
    sys.exit(1)
print("PASS %d checks, %d features, %d entities" % (checks, len(MODEL["features"]), len(MODEL["entities"])))
